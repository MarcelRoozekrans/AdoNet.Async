using System.Collections.Immutable;
using FluentAssertions;
using System.Data.Async.DataSet.Generator.Emit;
using System.Data.Async.DataSet.Generator.Model;
using Xunit;

namespace System.Data.Async.DataSet.Generator.Tests.Emit;

public class DataSetEmitterTests
{
    private static string EmitSimpleDataSet()
    {
        return DataSetEmitter.Emit(TestModels.SimpleDataSet);
    }

    [Fact]
    public void Emit_ContainsAutoGeneratedHeader()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("// <auto-generated/>");
    }

    [Fact]
    public void Emit_ContainsNullableEnable()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("#nullable enable");
    }

    [Fact]
    public void Emit_ContainsNamespace()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("namespace System.Data.Async.DataSet;");
    }

    [Fact]
    public void Emit_ContainsGeneratedCodeAttribute()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("[global::System.CodeDom.Compiler.GeneratedCode(\"AdoNet.Async.DataSet.Generator\", \"1.0.0\")]");
    }

    [Fact]
    public void Emit_ClassName()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("public partial class AsyncOrdersDS : AsyncDataSet");
    }

    [Fact]
    public void Emit_TypedTableFields()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("private AsyncOrdersDSCustomerDataTable tableCustomer = null!;");
        source.Should().Contain("private AsyncOrdersDSOrderDataTable tableOrder = null!;");
    }

    [Fact]
    public void Emit_RelationField()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("private global::System.Data.DataRelation relationFK_Customer_Order = null!;");
    }

    [Fact]
    public void Emit_TypedTableAccessors()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("public AsyncOrdersDSCustomerDataTable Customer => tableCustomer;");
        source.Should().Contain("public AsyncOrdersDSOrderDataTable Order => tableOrder;");
    }

    [Fact]
    public void Emit_RelationAccessor()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("public global::System.Data.DataRelation FK_Customer_Order => relationFK_Customer_Order;");
    }

    [Fact]
    public void Emit_InitClass_SetsDataSetName()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("inner.DataSetName = \"OrdersDS\";");
    }

    [Fact]
    public void Emit_InitClass_SetsLocale()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("new global::System.Globalization.CultureInfo(\"en-US\")");
    }

    [Fact]
    public void Emit_InitClass_SetsCaseSensitive()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("inner.CaseSensitive = false;");
    }

    [Fact]
    public void Emit_InitClass_SetsEnforceConstraints()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("inner.EnforceConstraints = true;");
    }

    [Fact]
    public void Emit_InitClass_CreatesTypedTables()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("tableCustomer = new AsyncOrdersDSCustomerDataTable();");
        source.Should().Contain("inner.Tables.Add((global::System.Data.DataTable)tableCustomer);");
    }

    [Fact]
    public void Emit_InitClass_CreatesRelation()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("relationFK_Customer_Order = new global::System.Data.DataRelation(\"FK_Customer_Order\"");
        source.Should().Contain("inner.Relations.Add(relationFK_Customer_Order);");
    }

    [Fact]
    public void Emit_InitVars_ResolvesTablesAndRelations()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("inner.Tables[\"Customer\"]");
        source.Should().Contain("inner.Tables[\"Order\"]");
        source.Should().Contain("relationFK_Customer_Order = inner.Relations[\"FK_Customer_Order\"]!;");
    }

    [Fact]
    public void Emit_InitExpressions()
    {
        var source = EmitSimpleDataSet();
        // Order table has a Total column with expression
        source.Should().Contain("tableOrder.TotalColumn.Expression = \"Price * Qty\";");
    }

    [Fact]
    public void Emit_Clone()
    {
        var source = EmitSimpleDataSet();
        source.Should().Contain("public new AsyncOrdersDS Clone()");
        source.Should().Contain("var clone = new AsyncOrdersDS();");
        source.Should().Contain("clone.InitVars();");
    }

    [Fact]
    public void Emit_NoLocale_Omitted()
    {
        var model = new DataSetModel(
            "TestDS", null, null, false, true,
            ImmutableArray<TableModel>.Empty,
            ImmutableArray<RelationModel>.Empty,
            ImmutableArray<ForeignKeyConstraintModel>.Empty);

        var source = DataSetEmitter.Emit(model);
        source.Should().NotContain("CultureInfo");
    }

    [Fact]
    public void Emit_ForeignKeyConstraint()
    {
        var fk = new ForeignKeyConstraintModel(
            "FK_Test",
            "Customer",
            ImmutableArray.Create("CustomerId"),
            "Order",
            ImmutableArray.Create("CustomerId"),
            "Cascade",
            "None",
            "None");

        var model = new DataSetModel(
            "OrdersDS", null, null, false, true,
            ImmutableArray.Create(TestModels.CustomerTable, TestModels.OrderTable),
            ImmutableArray<RelationModel>.Empty,
            ImmutableArray.Create(fk));

        var source = DataSetEmitter.Emit(model);
        source.Should().Contain("new global::System.Data.ForeignKeyConstraint(\"FK_Test\"");
        source.Should().Contain("AcceptRejectRule = global::System.Data.AcceptRejectRule.None");
        source.Should().Contain("DeleteRule = global::System.Data.Rule.None");
        source.Should().Contain("UpdateRule = global::System.Data.Rule.Cascade");
    }
}
