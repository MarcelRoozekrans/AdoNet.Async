using System.Collections.Immutable;
using FluentAssertions;
using System.Data.Async.DataSet.Generator.Emit;
using System.Data.Async.DataSet.Generator.Model;
using Xunit;

namespace System.Data.Async.DataSet.Generator.Tests.Emit;

public class DataTableEmitterTests
{
    private static string EmitCustomerTable()
    {
        return DataTableEmitter.Emit(
            "OrdersDS",
            TestModels.CustomerTable,
            ImmutableArray.Create(TestModels.CustomerOrderRelation));
    }

    private static string EmitOrderTable()
    {
        return DataTableEmitter.Emit(
            "OrdersDS",
            TestModels.OrderTable,
            ImmutableArray.Create(TestModels.CustomerOrderRelation));
    }

    [Fact]
    public void Emit_ContainsAutoGeneratedHeader()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("// <auto-generated/>");
    }

    [Fact]
    public void Emit_ContainsNullableEnable()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("#nullable enable");
    }

    [Fact]
    public void Emit_ContainsNamespace()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("namespace System.Data.Async.DataSet;");
    }

    [Fact]
    public void Emit_ContainsGeneratedCodeAttribute()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("[global::System.CodeDom.Compiler.GeneratedCode(\"AdoNet.Async.DataSet.Generator\", \"1.0.0\")]");
    }

    [Fact]
    public void Emit_Customer_ClassName()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("public partial class AsyncCustomerDataTable : AsyncDataTable<AsyncCustomerRow>");
    }

    [Fact]
    public void Emit_Customer_ColumnFields()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("private global::System.Data.DataColumn columnCustomerId = null!;");
        source.Should().Contain("private global::System.Data.DataColumn columnName = null!;");
        source.Should().Contain("private global::System.Data.DataColumn columnEmail = null!;");
    }

    [Fact]
    public void Emit_Customer_ColumnProperties()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("public global::System.Data.DataColumn CustomerIdColumn => columnCustomerId;");
    }

    [Fact]
    public void Emit_Customer_Count()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("public int Count => ((global::System.Data.DataTable)this).Rows.Count;");
    }

    [Fact]
    public void Emit_Customer_Indexer()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("public new AsyncCustomerRow this[int index] => WrapRow(((global::System.Data.DataTable)this).Rows[index]);");
    }

    [Fact]
    public void Emit_Customer_WrapRow()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("protected override AsyncCustomerRow WrapRow(global::System.Data.DataRow innerRow) => new AsyncCustomerRow(innerRow, this);");
    }

    [Fact]
    public void Emit_Customer_NewRow()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("public AsyncCustomerRow NewCustomerRow() => WrapRow(((global::System.Data.DataTable)this).NewRow());");
    }

    [Fact]
    public void Emit_Customer_AddRowAsync()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("AddCustomerRowAsync");
        source.Should().Contain("global::System.Threading.CancellationToken ct = default");
    }

    [Fact]
    public void Emit_Customer_RemoveRowAsync()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("RemoveCustomerRowAsync(AsyncCustomerRow row");
    }

    [Fact]
    public void Emit_Customer_FindBy()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("public AsyncCustomerRow? FindByCustomerId(int customerId)");
        source.Should().Contain("((global::System.Data.DataTable)this).Rows.Find");
    }

    [Fact]
    public void Emit_Customer_InitClass_CreatesColumns()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("columnCustomerId = new global::System.Data.DataColumn(\"CustomerId\"");
        source.Should().Contain("dt.Columns.Add(columnCustomerId);");
    }

    [Fact]
    public void Emit_Customer_InitClass_SetsPrimaryKey()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("dt.PrimaryKey = new global::System.Data.DataColumn[] { columnCustomerId }");
    }

    [Fact]
    public void Emit_Customer_InitVars_ResolvesColumns()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("columnCustomerId = dt.Columns[\"CustomerId\"]!;");
    }

    [Fact]
    public void Emit_Order_AutoIncrementColumn_SetInInitClass()
    {
        var source = EmitOrderTable();
        source.Should().Contain("columnOrderId.AutoIncrement = true;");
        source.Should().Contain("columnOrderId.AutoIncrementSeed = 1;");
        source.Should().Contain("columnOrderId.AutoIncrementStep = 1;");
    }

    [Fact]
    public void Emit_Order_AddRow_ExcludesAutoIncrementColumn()
    {
        var source = EmitOrderTable();
        // AddOrderRowAsync should not include orderId as a parameter
        source.Should().Contain("AddOrderRowAsync");
        // The method parameters should not mention orderId directly
        // but should have customerId (possibly as parent row) and orderDate
    }

    [Fact]
    public void Emit_Order_ExpressionColumn_InInitClass()
    {
        var source = EmitOrderTable();
        source.Should().Contain("columnTotal.Expression = \"Price * Qty\";");
    }

    [Fact]
    public void Emit_TypedTable_UsesTypedPlural()
    {
        var source = DataTableEmitter.Emit(
            "DS",
            TestModels.TypedCategoryTable,
            ImmutableArray<RelationModel>.Empty);

        source.Should().Contain("public partial class AsyncCategoriesDataTable : AsyncDataTable<AsyncCategoryEntryRow>");
    }

    [Fact]
    public void Emit_Constructor_Default()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("public AsyncCustomerDataTable() : base(\"Customer\")");
        source.Should().Contain("InitClass();");
    }

    [Fact]
    public void Emit_Constructor_FromDataTable()
    {
        var source = EmitCustomerTable();
        source.Should().Contain("internal AsyncCustomerDataTable(global::System.Data.DataTable table) : base(table)");
        source.Should().Contain("InitVars();");
    }
}
