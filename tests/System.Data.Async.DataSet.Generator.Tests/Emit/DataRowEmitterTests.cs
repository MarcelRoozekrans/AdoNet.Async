using System.Collections.Immutable;
using FluentAssertions;
using System.Data.Async.DataSet.Generator.Emit;
using System.Data.Async.DataSet.Generator.Model;
using Xunit;

namespace System.Data.Async.DataSet.Generator.Tests.Emit;

public class DataRowEmitterTests
{
    private static string EmitCustomerRow()
    {
        return DataRowEmitter.Emit(
            "OrdersDS",
            TestModels.CustomerTable,
            ImmutableArray.Create(TestModels.CustomerOrderRelation),
            ImmutableArray.Create(TestModels.CustomerTable, TestModels.OrderTable));
    }

    private static string EmitOrderRow()
    {
        return DataRowEmitter.Emit(
            "OrdersDS",
            TestModels.OrderTable,
            ImmutableArray.Create(TestModels.CustomerOrderRelation),
            ImmutableArray.Create(TestModels.CustomerTable, TestModels.OrderTable));
    }

    [Fact]
    public void Emit_ContainsAutoGeneratedHeader()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("// <auto-generated/>");
    }

    [Fact]
    public void Emit_ContainsNullableEnable()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("#nullable enable");
    }

    [Fact]
    public void Emit_ContainsNamespace()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("namespace System.Data.Async.DataSet;");
    }

    [Fact]
    public void Emit_ContainsGeneratedCodeAttribute()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("[global::System.CodeDom.Compiler.GeneratedCode(\"AdoNet.Async.DataSet.Generator\", \"1.0.0\")]");
    }

    [Fact]
    public void Emit_Customer_ClassName()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("public partial class AsyncOrdersDSCustomerRow : AsyncDataRow");
    }

    [Fact]
    public void Emit_Customer_TypedProperty_NonNullable()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("public int CustomerId => (int)this[\"CustomerId\"];");
        source.Should().Contain("public string Name => (string)this[\"Name\"];");
    }

    [Fact]
    public void Emit_Customer_NullableProperty_ReturnNull()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("public string? Email => IsNull(\"Email\") ? null : (string)this[\"Email\"];");
    }

    [Fact]
    public void Emit_Customer_AsyncSetter()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("public global::System.Threading.Tasks.ValueTask SetCustomerIdAsync(int value, global::System.Threading.CancellationToken ct = default)");
        source.Should().Contain("=> SetValueAsync(\"CustomerId\", value, ct);");
    }

    [Fact]
    public void Emit_Customer_IsNullMethod()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("public bool IsEmailNull() => IsNull(\"Email\");");
    }

    [Fact]
    public void Emit_Customer_SetNullAsyncMethod()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("public global::System.Threading.Tasks.ValueTask SetEmailNullAsync(global::System.Threading.CancellationToken ct = default)");
        source.Should().Contain("=> SetValueAsync(\"Email\", global::System.DBNull.Value, ct);");
    }

    [Fact]
    public void Emit_Customer_ChildRelationAccessor()
    {
        var source = EmitCustomerRow();
        source.Should().Contain("public AsyncOrdersDSOrderRow[] GetOrderRows()");
        source.Should().Contain("GetChildRows(InnerRow.Table.ChildRelations[\"FK_Customer_Order\"])");
    }

    [Fact]
    public void Emit_Order_ParentRelationAccessor()
    {
        var source = EmitOrderRow();
        source.Should().Contain("public AsyncOrdersDSCustomerRow? CustomerRow");
        source.Should().Contain("GetParentRow(InnerRow.Table.ParentRelations[\"FK_Customer_Order\"])");
    }

    [Fact]
    public void Emit_Order_ReadOnlyExpressionColumn_NoSetter()
    {
        var source = EmitOrderRow();
        // Total is ReadOnly + Expression, so no setter should be generated
        source.Should().NotContain("SetTotalAsync");
    }

    [Fact]
    public void Emit_Order_ReturnEmpty_NullBehavior()
    {
        var source = EmitOrderRow();
        // Notes has ReturnEmpty behavior for string
        source.Should().Contain("public string Notes => IsNull(\"Notes\") ? \"\" : (string)this[\"Notes\"];");
    }

    [Fact]
    public void Emit_Order_AutoIncrementColumn_StillHasProperty()
    {
        var source = EmitOrderRow();
        source.Should().Contain("public int OrderId => (int)this[\"OrderId\"];");
    }

    [Fact]
    public void Emit_ReplacementValue_NullBehavior()
    {
        var table = new TableModel(
            "Product",
            null,
            null,
            ImmutableArray.Create(
                TestModels.Column("Id", "System.Int32"),
                TestModels.Column("Notes", "System.String", allowNull: true,
                    nullBehavior: NullValueBehaviorKind.ReplacementValue, replacementValue: "N/A")
            ),
            ImmutableArray.Create("Id"),
            ImmutableArray<UniqueConstraintModel>.Empty);

        var source = DataRowEmitter.Emit("DS", table,
            ImmutableArray<RelationModel>.Empty,
            ImmutableArray.Create(table));

        source.Should().Contain("IsNull(\"Notes\") ? \"N/A\" : (string)this[\"Notes\"]");
    }

    [Fact]
    public void Emit_Throw_NullBehavior()
    {
        var table = new TableModel(
            "Product",
            null,
            null,
            ImmutableArray.Create(
                TestModels.Column("Id", "System.Int32"),
                TestModels.Column("Price", "System.Decimal", allowNull: true,
                    nullBehavior: NullValueBehaviorKind.Throw)
            ),
            ImmutableArray.Create("Id"),
            ImmutableArray<UniqueConstraintModel>.Empty);

        var source = DataRowEmitter.Emit("DS", table,
            ImmutableArray<RelationModel>.Empty,
            ImmutableArray.Create(table));

        source.Should().Contain("throw new global::System.Data.StrongTypingException");
    }

    [Fact]
    public void Emit_HiddenColumn_Skipped()
    {
        var table = new TableModel(
            "T",
            null,
            null,
            ImmutableArray.Create(
                TestModels.Column("Id", "System.Int32"),
                TestModels.Column("HiddenCol", "System.String", isHidden: true)
            ),
            ImmutableArray.Create("Id"),
            ImmutableArray<UniqueConstraintModel>.Empty);

        var source = DataRowEmitter.Emit("DS", table,
            ImmutableArray<RelationModel>.Empty,
            ImmutableArray.Create(table));

        source.Should().NotContain("HiddenCol");
    }
}
