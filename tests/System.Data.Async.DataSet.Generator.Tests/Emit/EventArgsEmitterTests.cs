using System.Collections.Immutable;
using FluentAssertions;
using System.Data.Async.DataSet.Generator.Emit;
using System.Data.Async.DataSet.Generator.Model;
using Xunit;

namespace System.Data.Async.DataSet.Generator.Tests.Emit;

public class EventArgsEmitterTests
{
    [Fact]
    public void Emit_ContainsAutoGeneratedHeader()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("// <auto-generated/>");
    }

    [Fact]
    public void Emit_ContainsNullableEnable()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("#nullable enable");
    }

    [Fact]
    public void Emit_ContainsNamespace()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("namespace System.Data.Async.DataSet;");
    }

    [Fact]
    public void Emit_ContainsGeneratedCodeAttribute()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("[global::System.CodeDom.Compiler.GeneratedCode(\"AdoNet.Async.DataSet.Generator\", \"1.0.0\")]");
    }

    [Fact]
    public void Emit_Customer_ClassName()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("public sealed partial class AsyncOrdersDSCustomerRowChangeEvent");
    }

    [Fact]
    public void Emit_Customer_Constructor()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("public AsyncOrdersDSCustomerRowChangeEvent(AsyncOrdersDSCustomerRow row, global::System.Data.DataRowAction action)");
    }

    [Fact]
    public void Emit_Customer_RowProperty()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("public AsyncOrdersDSCustomerRow Row { get; }");
    }

    [Fact]
    public void Emit_Customer_ActionProperty()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("public global::System.Data.DataRowAction Action { get; }");
    }

    [Fact]
    public void Emit_TypedName_UsesTypedName()
    {
        var source = EventArgsEmitter.Emit("DS", TestModels.TypedCategoryTable);
        source.Should().Contain("public sealed partial class AsyncDSCategoryEntryRowChangeEvent");
        source.Should().Contain("AsyncDSCategoryEntryRow row");
        source.Should().Contain("public AsyncDSCategoryEntryRow Row { get; }");
    }

    [Fact]
    public void Emit_AssignsRowAndAction()
    {
        var source = EventArgsEmitter.Emit("OrdersDS", TestModels.CustomerTable);
        source.Should().Contain("Row = row;");
        source.Should().Contain("Action = action;");
    }
}
