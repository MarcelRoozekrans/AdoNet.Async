using System.Collections.Immutable;
using System.Data.Async.DataSet.Generator.Model;
using System.Linq;
using System.Text;

namespace System.Data.Async.DataSet.Generator.Emit;

internal static class DataTableEmitter
{
    public static string Emit(
        string dataSetName,
        TableModel table,
        ImmutableArray<RelationModel> allRelations,
        ImmutableArray<TableModel> allTables)
    {
        var rowClass = NamingHelper.RowClassName(dataSetName, table.Name, table.TypedName);
        var tableClass = NamingHelper.TableClassName(dataSetName, table.Name, table.TypedPlural);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace System.Data.Async.DataSet;");
        sb.AppendLine();
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"AdoNet.Async.DataSet.Generator\", \"1.0.0\")]");
        sb.AppendLine($"public partial class {tableClass} : AsyncDataTable<{rowClass}>");
        sb.AppendLine("{");

        // Private DataColumn fields
        foreach (var col in table.Columns)
        {
            sb.AppendLine($"    private global::System.Data.DataColumn column{col.Name} = null!;");
        }

        sb.AppendLine();

        // Constructor
        sb.AppendLine($"    public {tableClass}() : base(\"{table.Name}\")");
        sb.AppendLine("    {");
        sb.AppendLine("        InitClass();");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Internal constructor from existing DataTable
        sb.AppendLine($"    internal {tableClass}(global::System.Data.DataTable table) : base(table)");
        sb.AppendLine("    {");
        sb.AppendLine("        InitVars();");
        sb.AppendLine("    }");

        // Column properties
        foreach (var col in table.Columns)
        {
            sb.AppendLine();
            sb.AppendLine($"    public global::System.Data.DataColumn {col.Name}Column => column{col.Name};");
        }

        // Count property
        sb.AppendLine();
        sb.AppendLine($"    public int Count => (InnerDataTable).Rows.Count;");

        // Typed indexer — hides base, use new
        sb.AppendLine();
        sb.AppendLine($"    public new {rowClass} this[int index] => WrapRow((InnerDataTable).Rows[index]);");

        // WrapRow override
        sb.AppendLine();
        sb.AppendLine($"    protected override {rowClass} WrapRow(global::System.Data.DataRow innerRow) => new {rowClass}(innerRow, this);");

        // NewXxxRow
        var newRowMethod = NamingHelper.NewRowMethodName(table.Name, table.TypedName);
        sb.AppendLine();
        sb.AppendLine($"    public {rowClass} {newRowMethod}() => WrapRow((InnerDataTable).NewRow());");

        // AddXxxRowAsync - with typed parameters, returns the row
        EmitAddRowMethod(sb, dataSetName, table, rowClass, allRelations, allTables);

        // RemoveXxxRowAsync
        var removeRowMethod = NamingHelper.RemoveRowMethodName(table.Name, table.TypedName);
        sb.AppendLine();
        sb.AppendLine($"    public global::System.Threading.Tasks.ValueTask {removeRowMethod}({rowClass} row, global::System.Threading.CancellationToken ct = default)");
        sb.AppendLine("        => Rows.RemoveAsync(row, ct);");

        // FindByXxx for primary keys
        if (table.PrimaryKeyColumnNames.Length > 0)
        {
            EmitFindByMethod(sb, table, rowClass);
        }

        // InitClass
        EmitInitClass(sb, table);

        // InitVars
        EmitInitVars(sb, table);

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitAddRowMethod(
        StringBuilder sb,
        string dataSetName,
        TableModel table,
        string rowClass,
        ImmutableArray<RelationModel> allRelations,
        ImmutableArray<TableModel> allTables)
    {
        var addRowMethod = NamingHelper.AddRowMethodName(table.Name, table.TypedName);

        // Build parameter list: exclude AutoIncrement columns and hidden columns
        // For FK columns that have a relation, use the parent row type instead
        var parameters = new System.Collections.Generic.List<string>();
        var assignments = new System.Collections.Generic.List<string>();

        // Collect FK child columns for this table
        var fkChildColumns = new System.Collections.Generic.Dictionary<string, RelationModel>(StringComparer.Ordinal);
        foreach (var rel in allRelations)
        {
            if (rel.ConstraintOnly)
                continue;
            if (!string.Equals(rel.ChildTableName, table.Name, StringComparison.Ordinal))
                continue;
            foreach (var childCol in rel.ChildColumnNames)
            {
                if (!fkChildColumns.ContainsKey(childCol))
                    fkChildColumns[childCol] = rel;
            }
        }

        // Track which relations we've already added a parent row parameter for
        var addedParentParams = new System.Collections.Generic.HashSet<string>(StringComparer.Ordinal);

        foreach (var col in table.Columns)
        {
            if (col.IsHidden || col.AutoIncrement || col.Expression != null || col.ReadOnly)
                continue;

            if (fkChildColumns.TryGetValue(col.Name, out var rel) && addedParentParams.Add(rel.Name))
            {
                // Use parent row type as parameter — look up the parent table's typedName for correct class name
                var parentTable = FindTable(allTables, rel.ParentTableName);
                var parentRowClass = NamingHelper.RowClassName(dataSetName, rel.ParentTableName, parentTable?.TypedName);
                var paramName = $"parent{rel.ParentTableName}Row";
                parameters.Add($"{parentRowClass}? {paramName}");

                // Assign FK columns from parent row via InnerRow
                for (int i = 0; i < rel.ChildColumnNames.Length; i++)
                {
                    assignments.Add($"            if ({paramName} != null) row[\"{rel.ChildColumnNames[i]}\"] = {paramName}[\"{rel.ParentColumnNames[i]}\"];");
                }
            }
            else if (!fkChildColumns.ContainsKey(col.Name))
            {
                var keyword = NamingHelper.ClrTypeToKeyword(col.ClrTypeName);
                parameters.Add($"{keyword} {ToCamelCase(col.Name)}");
                assignments.Add($"            row[\"{col.Name}\"] = {ToCamelCase(col.Name)};");
            }
        }

        sb.AppendLine();
        sb.Append($"    public async global::System.Threading.Tasks.ValueTask<{rowClass}> {addRowMethod}(");
        sb.Append(string.Join(", ", parameters));
        sb.AppendLine(", global::System.Threading.CancellationToken ct = default)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var row = (InnerDataTable).NewRow();");
        for (int i = 0; i < assignments.Count; i++)
        {
            sb.AppendLine(assignments[i]);
        }
        sb.AppendLine($"        var typedRow = WrapRow(row);");
        sb.AppendLine("        await Rows.AddAsync(typedRow, ct).ConfigureAwait(false);");
        sb.AppendLine("        return typedRow;");
        sb.AppendLine("    }");
    }

    private static void EmitFindByMethod(StringBuilder sb, TableModel table, string rowClass)
    {
        var methodName = NamingHelper.FindByMethodName(table.PrimaryKeyColumnNames);

        var parameters = new System.Collections.Generic.List<string>();
        foreach (var pkColName in table.PrimaryKeyColumnNames)
        {
            ColumnModel? pkCol = null;
            foreach (var c in table.Columns)
            {
                if (string.Equals(c.Name, pkColName, StringComparison.Ordinal))
                {
                    pkCol = c;
                    break;
                }
            }
            if (pkCol != null)
            {
                var keyword = NamingHelper.ClrTypeToKeyword(pkCol.ClrTypeName);
                parameters.Add($"{keyword} {ToCamelCase(pkCol.Name)}");
            }
        }

        sb.AppendLine();
        sb.Append($"    public {rowClass}? {methodName}(");
        sb.Append(string.Join(", ", parameters));
        sb.AppendLine(")");
        sb.AppendLine("    {");
        sb.AppendLine($"        var row = (InnerDataTable).Rows.Find(new object[] {{ {string.Join(", ", table.PrimaryKeyColumnNames.Select(n => ToCamelCase(n)))} }});");
        sb.AppendLine($"        return row != null ? WrapRow(row) : null;");
        sb.AppendLine("    }");
    }

    private static void EmitInitClass(StringBuilder sb, TableModel table)
    {
        sb.AppendLine();
        sb.AppendLine("    private void InitClass()");
        sb.AppendLine("    {");
        sb.AppendLine("        var dt = InnerDataTable;");

        foreach (var col in table.Columns)
        {
            sb.AppendLine($"        column{col.Name} = new global::System.Data.DataColumn(\"{col.Name}\", typeof({NamingHelper.ClrTypeToKeyword(col.ClrTypeName)}), null, global::System.Data.MappingType.Element);");
            sb.AppendLine($"        dt.Columns.Add(column{col.Name});");

            if (col.AutoIncrement)
            {
                sb.AppendLine($"        column{col.Name}.AutoIncrement = true;");
                sb.AppendLine($"        column{col.Name}.AutoIncrementSeed = {col.AutoIncrementSeed};");
                sb.AppendLine($"        column{col.Name}.AutoIncrementStep = {col.AutoIncrementStep};");
            }

            if (!col.AllowDBNull)
            {
                sb.AppendLine($"        column{col.Name}.AllowDBNull = false;");
            }

            if (col.ReadOnly)
            {
                sb.AppendLine($"        column{col.Name}.ReadOnly = true;");
            }

            if (col.DefaultValue != null)
            {
                sb.AppendLine($"        column{col.Name}.DefaultValue = \"{EscapeString(col.DefaultValue)}\";");
            }

            if (col.Caption != null)
            {
                sb.AppendLine($"        column{col.Name}.Caption = \"{EscapeString(col.Caption)}\";");
            }

            if (col.MaxLength.HasValue)
            {
                sb.AppendLine($"        column{col.Name}.MaxLength = {col.MaxLength.Value};");
            }

            if (col.Expression != null)
            {
                sb.AppendLine($"        column{col.Name}.Expression = \"{EscapeString(col.Expression)}\";");
            }
        }

        // Set primary key
        if (table.PrimaryKeyColumnNames.Length > 0)
        {
            sb.Append("        dt.PrimaryKey = new global::System.Data.DataColumn[] { ");
            sb.Append(string.Join(", ", table.PrimaryKeyColumnNames.Select(n => $"column{n}")));
            sb.AppendLine(" };");
        }

        sb.AppendLine("    }");
    }

    private static void EmitInitVars(StringBuilder sb, TableModel table)
    {
        sb.AppendLine();
        sb.AppendLine("    internal void InitVars()");
        sb.AppendLine("    {");
        sb.AppendLine("        var dt = InnerDataTable;");
        foreach (var col in table.Columns)
        {
            sb.AppendLine($"        column{col.Name} = dt.Columns[\"{col.Name}\"]!;");
        }
        sb.AppendLine("    }");
    }

    private static string ToCamelCase(string name)
    {
        if (string.IsNullOrEmpty(name))
            return name;
        return $"{char.ToLowerInvariant(name[0])}{name.Substring(1)}";
    }

    private static string EscapeString(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }

    private static TableModel? FindTable(ImmutableArray<TableModel> tables, string name)
    {
        foreach (var t in tables)
        {
            if (string.Equals(t.Name, name, StringComparison.Ordinal))
                return t;
        }
        return null;
    }
}
