using System.Collections.Immutable;
using System.Data.Async.DataSet.Generator.Model;
using System.Text;

namespace System.Data.Async.DataSet.Generator.Emit;

internal static class DataRowEmitter
{
    public static string Emit(
        string dataSetName,
        TableModel table,
        ImmutableArray<RelationModel> allRelations,
        ImmutableArray<TableModel> allTables)
    {
        var rowClass = NamingHelper.RowClassName(table.Name, table.TypedName);
        var tableClass = NamingHelper.TableClassName(table.Name, table.TypedPlural);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace System.Data.Async.DataSet;");
        sb.AppendLine();
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"AdoNet.Async.DataSet.Generator\", \"1.0.0\")]");
        sb.AppendLine($"public partial class {rowClass} : AsyncDataRow");
        sb.AppendLine("{");

        // Private field for typed table
        sb.AppendLine($"    private readonly {tableClass} _table;");
        sb.AppendLine();

        // Constructor
        sb.AppendLine($"    internal {rowClass}(global::System.Data.DataRow inner, {tableClass} table) : base(inner)");
        sb.AppendLine("    {");
        sb.AppendLine("        _table = table;");
        sb.AppendLine("    }");

        // Typed column properties
        foreach (var col in table.Columns)
        {
            if (col.IsHidden)
                continue;

            var keyword = NamingHelper.ClrTypeToKeyword(col.ClrTypeName);
            sb.AppendLine();

            if (col.AllowDBNull)
            {
                EmitNullableProperty(sb, col, keyword);
            }
            else
            {
                sb.AppendLine($"    public {keyword} {col.Name} => ({keyword})this[\"{col.Name}\"];");
            }
        }

        // Async setters for mutable columns
        foreach (var col in table.Columns)
        {
            if (col.IsHidden || col.ReadOnly || col.Expression != null)
                continue;

            var keyword = NamingHelper.ClrTypeToKeyword(col.ClrTypeName);
            var setterName = NamingHelper.SetterMethodName(col.Name);
            sb.AppendLine();
            sb.AppendLine($"    public global::System.Threading.Tasks.ValueTask {setterName}({keyword} value, global::System.Threading.CancellationToken ct = default)");
            sb.AppendLine($"        => SetValueAsync(\"{col.Name}\", value, ct);");
        }

        // IsXxxNull and SetXxxNullAsync for nullable columns
        foreach (var col in table.Columns)
        {
            if (col.IsHidden || !col.AllowDBNull)
                continue;

            var isNullName = NamingHelper.IsNullMethodName(col.Name);
            var setNullName = NamingHelper.SetNullMethodName(col.Name);
            sb.AppendLine();
            sb.AppendLine($"    public bool {isNullName}() => IsNull(\"{col.Name}\");");
            sb.AppendLine();
            sb.AppendLine($"    public global::System.Threading.Tasks.ValueTask {setNullName}(global::System.Threading.CancellationToken ct = default)");
            sb.AppendLine($"        => SetValueAsync(\"{col.Name}\", global::System.DBNull.Value, ct);");
        }

        // Child relation accessors (this table is the parent)
        foreach (var rel in allRelations)
        {
            if (rel.ConstraintOnly)
                continue;
            if (!string.Equals(rel.ParentTableName, table.Name, StringComparison.Ordinal))
                continue;

            var childTable = FindTable(allTables, rel.ChildTableName);
            if (childTable == null)
                continue;

            var childRowClass = NamingHelper.RowClassName(childTable.Name, childTable.TypedName);
            var methodName = NamingHelper.GetChildRowsMethodName(childTable.Name, rel.TypedChildren);
            sb.AppendLine();
            sb.AppendLine($"    public {childRowClass}[] {methodName}()");
            sb.AppendLine("    {");
            sb.AppendLine($"        var innerRows = InnerRow.GetChildRows(InnerRow.Table.ChildRelations[\"{rel.Name}\"]);");
            sb.AppendLine($"        var result = new {childRowClass}[innerRows.Length];");
            sb.AppendLine("        for (int i = 0; i < innerRows.Length; i++)");
            sb.AppendLine("        {");
            // We need to find the child table to wrap. Use a simple new for now.
            sb.AppendLine($"            result[i] = new {childRowClass}(innerRows[i], null!);");
            sb.AppendLine("        }");
            sb.AppendLine("        return result;");
            sb.AppendLine("    }");
        }

        // Parent relation accessors (this table is the child)
        foreach (var rel in allRelations)
        {
            if (rel.ConstraintOnly)
                continue;
            if (!string.Equals(rel.ChildTableName, table.Name, StringComparison.Ordinal))
                continue;

            var parentTable = FindTable(allTables, rel.ParentTableName);
            if (parentTable == null)
                continue;

            var parentRowClass = NamingHelper.RowClassName(parentTable.Name, parentTable.TypedName);
            var propName = NamingHelper.ParentRowPropertyName(parentTable.Name, rel.TypedParent);
            var setMethodName = NamingHelper.SetParentRowMethodName(parentTable.Name, rel.TypedParent);
            sb.AppendLine();
            sb.AppendLine($"    public {parentRowClass}? {propName}");
            sb.AppendLine("    {");
            sb.AppendLine("        get");
            sb.AppendLine("        {");
            sb.AppendLine($"            var parentRow = InnerRow.GetParentRow(InnerRow.Table.ParentRelations[\"{rel.Name}\"]);");
            sb.AppendLine($"            return parentRow != null ? new {parentRowClass}(parentRow, null!) : null;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine($"    public global::System.Threading.Tasks.ValueTask {setMethodName}({parentRowClass}? value, global::System.Threading.CancellationToken ct = default)");
            sb.AppendLine("    {");
            sb.AppendLine("        // Setting parent row requires updating FK columns");
            sb.AppendLine("        if (value == null)");
            sb.AppendLine("        {");
            // Set FK columns to DBNull
            foreach (var childCol in rel.ChildColumnNames)
            {
                sb.AppendLine($"            this[\"{childCol}\"] = global::System.DBNull.Value;");
            }
            sb.AppendLine("        }");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
            for (int i = 0; i < rel.ChildColumnNames.Length; i++)
            {
                sb.AppendLine($"            this[\"{rel.ChildColumnNames[i]}\"] = value[\"{rel.ParentColumnNames[i]}\"];");
            }
            sb.AppendLine("        }");
            sb.AppendLine($"        return default;");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitNullableProperty(StringBuilder sb, ColumnModel col, string keyword)
    {
        switch (col.NullValueBehavior.Kind)
        {
            case NullValueBehaviorKind.Throw:
                sb.AppendLine($"    public {keyword} {col.Name}");
                sb.AppendLine("    {");
                sb.AppendLine("        get");
                sb.AppendLine("        {");
                sb.AppendLine($"            if (IsNull(\"{col.Name}\"))");
                sb.AppendLine($"                throw new global::System.Data.StrongTypingException(\"The value for column '{col.Name}' in table is DBNull.\", null);");
                sb.AppendLine($"            return ({keyword})this[\"{col.Name}\"];");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
                break;

            case NullValueBehaviorKind.ReturnNull:
                sb.AppendLine($"    public {keyword}? {col.Name} => IsNull(\"{col.Name}\") ? null : ({keyword})this[\"{col.Name}\"];");
                break;

            case NullValueBehaviorKind.ReturnEmpty:
                if (string.Equals(col.ClrTypeName, "System.String", StringComparison.Ordinal))
                {
                    sb.AppendLine($"    public {keyword} {col.Name} => IsNull(\"{col.Name}\") ? \"\" : ({keyword})this[\"{col.Name}\"];");
                }
                else
                {
                    sb.AppendLine($"    public {keyword} {col.Name} => IsNull(\"{col.Name}\") ? default({keyword}) : ({keyword})this[\"{col.Name}\"];");
                }
                break;

            case NullValueBehaviorKind.ReplacementValue:
                var replacement = col.NullValueBehavior.ReplacementValue ?? "default";
                if (string.Equals(col.ClrTypeName, "System.String", StringComparison.Ordinal))
                {
                    sb.AppendLine($"    public {keyword} {col.Name} => IsNull(\"{col.Name}\") ? \"{EscapeString(replacement)}\" : ({keyword})this[\"{col.Name}\"];");
                }
                else
                {
                    sb.AppendLine($"    public {keyword} {col.Name} => IsNull(\"{col.Name}\") ? {replacement} : ({keyword})this[\"{col.Name}\"];");
                }
                break;
        }
    }

    private static string EscapeString(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }

    private static TableModel? FindTable(ImmutableArray<TableModel> tables, string name)
    {
        foreach (var t in tables)
        {
            if (string.Equals(t.Name, name, StringComparison.Ordinal))
                return t;
        }
        return null;
    }
}
